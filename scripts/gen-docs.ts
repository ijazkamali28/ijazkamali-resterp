/**
 * Generates documentation from the live schema and the code-defined catalogues:
 *   docs/ERD.md          Mermaid ER diagrams per domain (from pg_catalog foreign keys)
 *   docs/SCHEMA.md       data dictionary: columns, types, nullability, defaults, keys, indexes, checks
 *   docs/PERMISSIONS.md  role x permission matrix
 *   docs/NAVIGATION.md   navigation tree with required permissions
 * Usage: npm run docs   (requires a migrated database at DATABASE_OWNER_URL)
 */
import 'dotenv/config';
import pg from 'pg';
import { writeFileSync } from 'node:fs';
import { PERMISSIONS, ROLES } from '../src/auth/permissions.js';
import { NAVIGATION, type NavItem } from '../src/modules/meta/navigation.js';

const DOMAINS: [string, string][] = [
  ['org', 'Organization & branches'], ['iam', 'Users & permissions'], ['crm', 'Customers'], ['menu', 'Menu, dishes & pricing'],
  ['recipe', 'Recipes'], ['pos', 'POS orders, tables & shifts'], ['pay', 'Payments'], ['inv', 'Inventory'], ['proc', 'Procurement'],
  ['supl', 'Suppliers'], ['kds', 'Kitchen'], ['dlv', 'Delivery & riders'], ['agg', 'Aggregators'], ['loy', 'Loyalty'],
  ['mkt', 'Marketing'], ['exp', 'Expenses'], ['acct', 'Accounting & tax'], ['sync', 'Synchronization'], ['audit', 'Audit'],
];
const SCHEMAS = DOMAINS.map(([s]) => s);
// columns that reference users/companies everywhere would drown the diagrams
const NOISY = new Set(['created_by', 'updated_by', 'company_id', 'approved_by', 'posted_by', 'requested_by', 'performed_by', 'received_by', 'voided_by', 'void_approved_by', 'variance_approved_by', 'closed_by', 'resolved_by', 'registered_by', 'submitted_by']);

const db = new pg.Client({ connectionString: process.env.DATABASE_OWNER_URL });
await db.connect();

const cols = (await db.query(`
  select c.table_schema s, c.table_name t, c.column_name col, c.ordinal_position pos,
         case when c.data_type = 'USER-DEFINED' then c.udt_name when c.data_type = 'ARRAY' then c.udt_name
              when c.character_maximum_length is not null then c.data_type || '(' || c.character_maximum_length || ')'
              when c.data_type = 'numeric' and c.numeric_precision is not null then 'numeric(' || c.numeric_precision || ',' || c.numeric_scale || ')'
              else c.data_type end as type,
         c.is_nullable = 'YES' nullable, c.column_default def, c.is_generated = 'ALWAYS' generated
    from information_schema.columns c join information_schema.tables tb using (table_schema, table_name)
   where c.table_schema = any($1) and tb.table_type = 'BASE TABLE' order by 1,2,4`, [SCHEMAS])).rows;

const cons = (await db.query(`
  select n.nspname s, c.relname t, k.conname name, k.contype type, pg_get_constraintdef(k.oid) def,
         fn.nspname fs, fc.relname ft, (select array_agg(a.attname::text order by x.ord) from unnest(k.conkey) with ordinality x(attnum, ord)
            join pg_attribute a on a.attrelid = k.conrelid and a.attnum = x.attnum) as cols
    from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
    left join pg_class fc on fc.oid = k.confrelid left join pg_namespace fn on fn.oid = fc.relnamespace
   where n.nspname = any($1) order by 1,2,3`, [SCHEMAS])).rows;

const idx = (await db.query(`select schemaname s, tablename t, indexname name, indexdef def from pg_indexes where schemaname = any($1) order by 1,2,3`, [SCHEMAS])).rows;
const rls = new Set((await db.query(`select n.nspname || '.' || c.relname t from pg_class c join pg_namespace n on n.oid = c.relnamespace where c.relrowsecurity and n.nspname = any($1)`, [SCHEMAS])).rows.map((r) => r.t));
const tracked = new Map((await db.query('select table_name, ownership, conflict_policy from sync.tracked_tables')).rows.map((r) => [r.table_name, r]));
const appendOnly = new Set((await db.query(`select n.nspname || '.' || c.relname t from pg_trigger g join pg_class c on c.oid = g.tgrelid join pg_namespace n on n.oid = c.relnamespace where g.tgname like '%append_only'`)).rows.map((r) => r.t));
await db.end();

const tables = [...new Set(cols.map((c) => `${c.s}.${c.t}`))];
const ent = (full: string) => full.replace('.', '__');

// ------------------------------------------------------------------ ERD
let erd = `# Entity relationship diagrams\n\n_Generated by \`npm run docs\` from the migrated database (${tables.length} tables). Do not edit by hand._\n\n`;
erd += `Conventions: every table has a UUID \`id\` primary key (except pure link/derived tables), \`company_id\` (tenant), and where operational \`branch_id\`.\n`;
erd += `Audit columns (\`created_by\`, \`updated_by\`, approvers) and \`company_id\` → \`org.companies\` links exist on almost every table and are omitted from the diagrams for readability; see SCHEMA.md.\n\n`;
erd += `## Domain overview\n\n\`\`\`mermaid\nflowchart LR\n`;
const domainEdges = new Set<string>();
for (const k of cons.filter((k) => k.type === 'f' && k.fs && k.fs !== k.s && !k.cols.every((c: string) => NOISY.has(c)))) domainEdges.add(`  ${k.s} --> ${k.fs}`);
erd += DOMAINS.map(([s, label]) => `  ${s}["${label}<br/>(${s})"]`).join('\n') + '\n' + [...domainEdges].sort().join('\n') + '\n```\n\n';

for (const [schema, label] of DOMAINS) {
  const own = tables.filter((t) => t.startsWith(schema + '.'));
  const fks = cons.filter((k) => k.type === 'f' && (k.s === schema) && !k.cols.every((c: string) => NOISY.has(c)));
  const external = new Set(fks.map((k) => `${k.fs}.${k.ft}`).filter((t) => !t.startsWith(schema + '.')));
  erd += `## ${label} (\`${schema}\`)\n\n\`\`\`mermaid\nerDiagram\n`;
  for (const t of own) {
    const [s, n] = t.split('.');
    const tc = cols.filter((c) => c.s === s && c.t === n && !['created_at', 'updated_at', 'created_by', 'updated_by', 'row_version'].includes(c.col));
    const pk = new Set(cons.filter((k) => k.s === s && k.t === n && k.type === 'p').flatMap((k) => k.cols));
    const fk = new Set(cons.filter((k) => k.s === s && k.t === n && k.type === 'f').flatMap((k) => k.cols));
    erd += `  ${ent(t)} {\n` + tc.map((c) => `    ${c.type.replace(/[^a-z0-9_]/gi, '_')} ${c.col}${pk.has(c.col) ? ' PK' : fk.has(c.col) ? ' FK' : ''}`).join('\n') + '\n  }\n';
  }
  for (const t of external) erd += `  ${ent(t)} {\n    uuid id PK\n  }\n`;
  const seen = new Set<string>();
  for (const k of fks) {
    const nullable = k.cols.some((c: string) => cols.find((x) => x.s === k.s && x.t === k.t && x.col === c)?.nullable);
    const line = `  ${ent(`${k.fs}.${k.ft}`)} ||--o{ ${ent(`${k.s}.${k.t}`)} : "${k.cols.join(',')}${nullable ? ' (opt)' : ''}"`;
    if (!seen.has(line)) { seen.add(line); erd += line + '\n'; }
  }
  erd += '```\n\n';
}
writeFileSync('docs/ERD.md', erd);

// ------------------------------------------------------------------ SCHEMA dictionary
let dict = `# Database schema (data dictionary)\n\n_Generated by \`npm run docs\`. ${tables.length} tables across ${DOMAINS.length} domains._\n\n`;
dict += `Legend: **RLS** = row-level security (company/branch isolation) · **Append-only** = UPDATE/DELETE blocked by trigger · **Sync** = replication ownership / conflict policy.\n\n`;
for (const [schema, label] of DOMAINS) {
  dict += `## ${label} — \`${schema}\`\n\n`;
  for (const t of tables.filter((x) => x.startsWith(schema + '.'))) {
    const [s, n] = t.split('.');
    const tr = tracked.get(t);
    const flags = [rls.has(t) ? 'RLS' : 'no RLS (global/bookkeeping)', appendOnly.has(t) ? 'Append-only' : null,
      tr ? `Sync: ${tr.ownership}/${tr.conflict_policy}` : 'Sync: not replicated'].filter(Boolean).join(' · ');
    dict += `### \`${t}\`\n\n${flags}\n\n| Column | Type | Required | Default |\n|---|---|---|---|\n`;
    for (const c of cols.filter((c) => c.s === s && c.t === n)) {
      dict += `| ${c.col} | ${c.type} | ${c.nullable ? '' : 'yes'} | ${c.generated ? '_generated_' : (c.def ?? '').replace(/\|/g, '\\|').slice(0, 60)} |\n`;
    }
    const k = cons.filter((k) => k.s === s && k.t === n);
    const fmt = (type: string, title: string) => {
      const list = k.filter((x) => x.type === type);
      return list.length ? `\n**${title}:**\n${list.map((x) => `- \`${x.def.replace(/\s+/g, ' ')}\``).join('\n')}\n` : '';
    };
    dict += fmt('p', 'Primary key') + fmt('f', 'Foreign keys') + fmt('u', 'Unique') + fmt('c', 'Checks');
    const ix = idx.filter((i) => i.s === s && i.t === n && !k.some((x) => x.name === i.name));
    if (ix.length) dict += `\n**Indexes:**\n${ix.map((i) => `- \`${i.def.replace(/^CREATE (UNIQUE )?INDEX \S+ ON \S+ USING btree /, (_m: string, u: string) => (u ? 'UNIQUE ' : ''))}\``).join('\n')}\n`;
    dict += '\n';
  }
}
writeFileSync('docs/SCHEMA.md', dict);

// ------------------------------------------------------------------ PERMISSIONS
const roleCols = ROLES.map((r) => r.code);
let perm = `# Permission matrix\n\n_Generated from \`src/auth/permissions.ts\` (single source of truth for seeding, enforcement and this document)._\n\n`;
perm += `## Roles\n\n| Code | Name | Scope | Description |\n|---|---|---|---|\n` + ROLES.map((r) => `| ${r.code} | ${r.name} | ${r.scope} | ${r.description} |`).join('\n');
perm += `\n\nScope: **platform** = all tenants; **company** = normally granted for all branches (\`branch_id\` null); **branch** = granted per branch.\n`;
perm += `A user may hold several roles in different branches; a permission is effective for a branch only if a grant for that branch (or a company-wide grant) includes it.\n\n`;
perm += `Rules enforced server-side: no self-role changes; a grantor must hold every permission of the role they grant, for the same branch; company-wide grants only by company-wide admins; sensitive (⚠) actions need a reason code and are audited.\n\n`;
perm += `## Matrix\n\n| Permission | ⚠ | ${roleCols.map((c) => c.replace(/_/g, ' ')).join(' | ')} |\n|---|---|${roleCols.map(() => ':-:').join('|')}|\n`;
for (const p of PERMISSIONS) {
  perm += `| \`${p.code}\` — ${p.description} | ${p.sensitive ? '⚠' : ''} | ${ROLES.map((r) => (r.permissions.includes(p.code) ? '✔' : '')).join(' | ')} |\n`;
}
writeFileSync('docs/PERMISSIONS.md', perm);

// ------------------------------------------------------------------ NAVIGATION
const navLines = (items: NavItem[], depth = 0): string[] => items.flatMap((i) => [
  `${'  '.repeat(depth)}- **${i.label}**${i.path ? ` \`${i.path}\`` : ''} — phase ${i.phase}${i.anyOf ? ` — requires any of: ${i.anyOf.map((p) => `\`${p}\``).join(', ')}` : ''}`,
  ...(i.children ? navLines(i.children, depth + 1) : []),
]);
writeFileSync('docs/NAVIGATION.md', `# Navigation structure\n\n_Generated from \`src/modules/meta/navigation.ts\`. The API serves the user-specific tree at \`GET /api/v1/meta/navigation\`; menu entries a user lacks permissions for are never sent to the client._\n\n${navLines(NAVIGATION).join('\n')}\n`);
console.log(`docs generated: ${tables.length} tables, ${PERMISSIONS.length} permissions, ${ROLES.length} roles`);
